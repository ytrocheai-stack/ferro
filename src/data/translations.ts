/** Traduce un término del dataset; si no está en el mapa, lo capitaliza tal cual. */
export function t(term: string | null | undefined): string {
  if (!term) return ''
  const lower = term.toLowerCase().trim()
  if (ES[lower]) return ES[lower]
  return term.charAt(0).toUpperCase() + term.slice(1)
}

